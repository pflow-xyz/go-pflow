// Package crmath is a portable, correctly rounded Pow.
//
// math.Pow is not correctly rounded, and neither is any platform libm's pow
// (measured on ODE step-controller inputs: 0.135% of calls wrong on macOS /
// arm64, 0.063% on glibc, more for Rust on wasm32), and each is wrong on
// different inputs. The ODE step controller's (1/err)^(1/(order+1)) then
// rounds differently from one implementation to the next; one ulp in one step
// moves every later step, and in a game search the order of moves whose
// guesses tie.
//
// Pow returns x^y rounded once to the nearest double (ties to even) on every
// input, using nothing but IEEE 754 + - * /, comparisons, integer arithmetic
// and bit casts. It is an operation-for-operation port of pflow-rs'
// pflow_solver::crmath (crates/pflow-solver/src/crmath.rs, the reference;
// read its module doc for the method), and the same as pflow-xyz's copies
// (internal/crmath, public/petri-crmath.js). testdata/pow.txt, a
// byte-identical copy of pflow-rs' tests/fixtures/crmath/pow.txt, holds all
// of them to the same bits.
//
// Every product is wrapped in float64(...): the Go spec lets a compiler fuse
// x*y + z into one rounding (arm64 does), and an explicit conversion forbids
// it, which keeps the arithmetic the same as Rust's on every machine.
package crmath

import (
	"math"
	"math/bits"
)

type dd struct{ hi, lo float64 }

func f(b uint64) float64 { return math.Float64frombits(b) }

