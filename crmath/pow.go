const (
	// 2^27 + 1, Veltkamp's splitter.
	splitter = 134217729.0
	two53    = 9007199254740992.0
	two63    = 9223372036854775808.0
)

func ddTable(t [][2]uint64) []dd {
	out := make([]dd, len(t))
	for i, p := range t {
		out[i] = dd{f(p[0]), f(p[1])}
	}
	return out
}

// Pow is x^y, correctly rounded, the same bits on every host. Special cases
// (zeros, infinities, NaN, negative bases) are C99 Annex F's, as math.Pow's.
func Pow(x, y float64) float64 {
	if y == 0 || x == 1 {
		return 1
	}
	if math.IsNaN(x) || math.IsNaN(y) {
		return math.NaN()
	}
	yc := yClass(y)
	if math.IsInf(y, 0) {
		ax := math.Abs(x)
		if ax == 1 {
			return 1
		}
		if (ax < 1) == (y > 0) {
			return 0
		}
		return math.Inf(1)
	}
	if x == 0 {
		odd := yc == yOdd
		if y < 0 {
			if odd {
				return 1 / x
			}
			return math.Inf(1)
		}
		if odd {
			return x
		}
		return 0
	}
	if math.IsInf(x, 0) {
		odd := yc == yOdd
		if x > 0 {
			if y < 0 {
				return 0
			}
			return math.Inf(1)
		}
		if y < 0 {
			if odd {
				return math.Copysign(0, -1)
			}
			return 0
		}
		if odd {
			return math.Inf(-1)
		}
		return math.Inf(1)
	}
	if x < 0 {
		switch yc {
		case yNotInteger:
			return math.NaN()
		case yOdd:
			return -powPos(-x, y)
		default:
			return powPos(-x, y)
		}
	}
	return powPos(x, y)
}

const (
	yNotInteger = iota
	yOdd
	yEven
)

func yClass(y float64) int {
	if !(math.Abs(y) < two53) {
		return yEven
	}
	t := math.Trunc(y)
	if t != y {
		return yNotInteger
	}
	if int64(t)&1 != 0 {
		return yOdd
	}
	return yEven
}

// powPos is x^y for finite x > 0 and finite y != 0.
func powPos(x, y float64) float64 {
	if x == 1 {
		return 1
	}
	m, e := reduce(x)
	// |y ln x| > 1024 for every double x != 1 once |y| >= 2^63.
	if !(math.Abs(y) < two63) {
		if (x > 1) == (y > 0) {
			return math.Inf(1)
		}
		return 0
	}
	t := ddMulF(lnDD(m, e), y)
	if t.hi > 709.79 {
		return math.Inf(1)
	}
	if t.hi < -745.2 {
		return 0
	}
	if t.hi > -708.0 && t.hi < 709.0 {
		p, k := expDD(t)
		if p.hi == p.hi+float64(p.lo*round) {
			return float64(p.hi * twoPow(k))
		}
	}
	return slow(m, e, y, t.hi)
}

// reduce is x = m 2^e, m in [sqrt(2)/2, sqrt(2)), for finite x > 0.
func reduce(x float64) (float64, int32) {
	b := math.Float64bits(x)
	ex := int32((b >> 52) & 0x7FF)
	if ex == 0 {
		// Subnormal: multiplying by 2^52 is exact.
		x = float64(x * f(0x4330000000000000))
		b = math.Float64bits(x)
		ex = int32((b>>52)&0x7FF) - 52
	}
	e := ex - 1022
	m := f((b &^ (0x7FF << 52)) | (1022 << 52))
	if m < sqrt2Over2 {
		m = float64(m * 2)
		e--
	}
	return m, e
}

// twoPow is 2^k, -1022 <= k <= 1023.
func twoPow(k int32) float64 { return f(uint64(k+1023) << 52) }

// nearest is the integer nearest q (half away from zero), |q| < 2^31.
func nearest(q float64) int32 {
	if q >= 0 {
		return int32(q + 0.5)
	}
	return -int32(0.5 - q)
}

func twoSum(a, b float64) (float64, float64) {
	s := a + b
	bb := s - a
	e := (a - (s - bb)) + (b - bb)
	return s, e
}

func quickTwoSum(a, b float64) (float64, float64) {
	s := a + b
	e := b - (s - a)
	return s, e
}

func split(a float64) (float64, float64) {
	t := float64(splitter * a)
	hi := t - (t - a)
	lo := a - hi
	return hi, lo
}

// twoProd is a*b exactly, as p + e (Dekker; no FMA, which wasm32 lacks).
func twoProd(a, b float64) (float64, float64) {
	p := float64(a * b)
	ah, al := split(a)
	bh, bl := split(b)
	e := ((float64(ah*bh) - p) + float64(ah*bl) + float64(al*bh)) + float64(al*bl)
	return p, e
}

func ddAdd(x, y dd) dd {
	s, e := twoSum(x.hi, y.hi)
	t, g := twoSum(x.lo, y.lo)
	e = e + t
	s, e = quickTwoSum(s, e)
	e = e + g
	s, e = quickTwoSum(s, e)
	return dd{s, e}
}

func ddNeg(x dd) dd { return dd{-x.hi, -x.lo} }

func ddMul(x, y dd) dd {
	p, e := twoProd(x.hi, y.hi)
	e = e + (float64(x.hi*y.lo) + float64(x.lo*y.hi))
	p, e = quickTwoSum(p, e)
	return dd{p, e}
}

func ddMulF(x dd, g float64) dd {
	p, e := twoProd(x.hi, g)
	e = e + float64(x.lo*g)
	p, e = quickTwoSum(p, e)
	return dd{p, e}
}

func ddDiv(a, b dd) dd {
	q1 := a.hi / b.hi
	r := ddAdd(a, ddNeg(ddMulF(b, q1)))
	q2 := r.hi / b.hi
	r = ddAdd(r, ddNeg(ddMulF(b, q2)))
	q3 := r.hi / b.hi
	q1, q2 = quickTwoSum(q1, q2)
	return ddAdd(dd{q1, q2}, dd{q3, 0})
}

// lnDD is ln(m 2^e) in double-double.
func lnDD(m float64, e int32) dd {
	// m - 1 is exact (Sterbenz).
	g := m - 1
	dh, dl := twoSum(2, g)
	s := ddDiv(dd{g, 0}, dd{dh, dl})
	s2 := ddMul(s, s)
	p := invOdd[len(invOdd)-1]
	for k := len(invOdd) - 2; k >= 0; k-- {
		p = ddAdd(ddMul(p, s2), invOdd[k])
	}
	lm := ddMul(s, p)
	lm = dd{float64(2 * lm.hi), float64(2 * lm.lo)}
	// e ln 2: e * ln2_1 is exact (ln2_1 has 32 significant bits, |e| < 2^11).
	fe := float64(e)
	p2, pe2 := twoProd(fe, ln2_2)
	h, l := twoSum(float64(fe*ln2_1), p2)
	l = l + (pe2 + float64(fe*ln2_3))
	h, l = quickTwoSum(h, l)
	return ddAdd(dd{h, l}, lm)
}

// expDD is exp(t) = p 2^k, for |t.hi| < 709.
func expDD(t dd) (dd, int32) {
	k := nearest(float64(t.hi * invLn2))
	fk := float64(k)
	h, l := twoSum(t.hi, -float64(fk*ln2_1))
	r := ddAdd(dd{h, l}, dd{t.lo, 0})
	p, pe := twoProd(fk, ln2_2)
	r = ddAdd(r, dd{-p, -pe})
	r = ddAdd(r, dd{-float64(fk * ln2_3), 0})
	s := invFact[len(invFact)-1]
	for n := len(invFact) - 2; n >= 0; n-- {
		s = ddAdd(ddMul(s, r), invFact[n])
	}
	return s, k
}

// The slow path.

// fx is unsigned fixed point: sum(fx[i] 2^(64 i)) / 2^320, low limb first;
// five fractional limbs and one integer limb.
type fx [6]uint64

func fxInt(n uint64) fx { return fx{0, 0, 0, 0, 0, n} }

// fxBit is 2^(n - 320), n < 384.
func fxBit(n uint) fx {
	var r fx
	r[n/64] = 1 << (n % 64)
	return r
}

func (a fx) isZero() bool {
	for _, l := range a {
		if l != 0 {
			return false
		}
	}
	return true
}

func (a fx) less(o fx) bool {
	for i := 5; i >= 0; i-- {
		if a[i] != o[i] {
			return a[i] < o[i]
		}
	}
	return false
}

func (a fx) add(o fx) fx {
	var r fx
	var c uint64
	for i := 0; i < 6; i++ {
		r[i], c = bits.Add64(a[i], o[i], c)
	}
	return r
}

// sub is a - o, o <= a.
func (a fx) sub(o fx) fx {
	var r fx
	var b uint64
	for i := 0; i < 6; i++ {
		r[i], b = bits.Sub64(a[i], o[i], b)
	}
	return r
}

// mul is a*o, truncated; the product must be below 2^64.
func (a fx) mul(o fx) fx {
	var w [12]uint64
	for i := 0; i < 6; i++ {
		var c uint64
		for j := 0; j < 6; j++ {
			hi, lo := bits.Mul64(a[i], o[j])
			var k uint64
			lo, k = bits.Add64(lo, w[i+j], 0)
			hi += k
			lo, k = bits.Add64(lo, c, 0)
			hi += k
			w[i+j] = lo
			c = hi
		}
		w[i+6] = c
	}
	return fx{w[5], w[6], w[7], w[8], w[9], w[10]}
}

// mulSmall is a*n; the product must be below 2^64.
func (a fx) mulSmall(n uint64) fx {
	var r fx
	var c uint64
	for i := 0; i < 6; i++ {
		hi, lo := bits.Mul64(a[i], n)
		var k uint64
		lo, k = bits.Add64(lo, c, 0)
		r[i] = lo
		c = hi + k
	}
	return r
}

// divSmall is a/d, truncated, d > 0.
func (a fx) divSmall(d uint64) fx {
	var r fx
	var rem uint64
	for i := 5; i >= 0; i-- {
		r[i], rem = bits.Div64(rem, a[i], d)
	}
	return r
}

func (a fx) shl(n uint) fx {
	var r fx
	w, b := int(n/64), n%64
	for i := 5; i >= w; i-- {
		v := a[i-w] << b
		if b > 0 && i > w {
			v |= a[i-w-1] >> (64 - b)
		}
		r[i] = v
	}
	return r
}

func (a fx) shr(n uint) fx {
	var r fx
	w, b := int(n/64), n%64
	for i := 0; i+w < 6; i++ {
		v := a[i+w] >> b
		if b > 0 && i+w+1 < 6 {
			v |= a[i+w+1] << (64 - b)
		}
		r[i] = v
	}
	return r
}

// low is the low n bits of a, n < 384.
func (a fx) low(n uint) fx {
	r := a
	w, b := int(n/64), n%64
	for i := 0; i < 6; i++ {
		if i > w || (i == w && b == 0) {
			r[i] = 0
		} else if i == w {
			r[i] &= (1 << b) - 1
		}
	}
	return r
}

// signedAdd is (an ? -a : a) + (bn ? -b : b) as a sign and a magnitude;
// zero is positive.
func signedAdd(an bool, a fx, bn bool, b fx) (bool, fx) {
	if an == bn {
		s := a.add(b)
		return an && !s.isZero(), s
	}
	if b.less(a) {
		return an, a.sub(b)
	}
	d := b.sub(a)
	return bn && !d.isZero(), d
}

func uabs(v int64) uint64 {
	if v < 0 {
		return uint64(-v)
	}
	return uint64(v)
}

// slow is x^y from x = m 2^e in 320-bit fixed point, rounded once. tHi
// approximates y ln x, which is within [-745.2, 709.79].
func slow(m float64, e int32, y, tHi float64) float64 {
	// m 2^53 is an integer below 2^54.
	bigM := uint64(float64(m * two53))
	const h = uint64(1) << 53
	sNeg, num := false, uint64(0)
	if bigM < h {
		sNeg, num = true, h-bigM
	} else {
		num = bigM - h
	}
	// s = (m - 1) / (m + 1); ln m = 2 atanh(s).
	s := fxInt(num).divSmall(bigM + h)
	s2 := s.mul(s)
	term, sum := s, s
	for k := uint64(1); ; k++ {
		term = term.mul(s2)
		if term.isZero() {
			break
		}
		sum = sum.add(term.divSmall(2*k + 1))
	}
	lnm := sum.shl(1)
	lNeg, l := signedAdd(sNeg, lnm, e < 0, ln2Fx.mulSmall(uabs(int64(e))))
	// t = y ln x, y = ym 2^ye.
	yb := math.Float64bits(y)
	yNeg := yb>>63 == 1
	yexp := int32((yb >> 52) & 0x7FF)
	var ym uint64
	var ye int32
	if yexp == 0 {
		ym, ye = yb&(1<<52-1), -1074
	} else {
		ym, ye = yb&(1<<52-1)|1<<52, yexp-1075
	}
	tm := l.mulSmall(ym)
	switch {
	case ye >= 0:
		tm = tm.shl(uint(ye))
	case ye > -384:
		tm = tm.shr(uint(-ye))
	default:
		tm = fx{}
	}
	tNeg := lNeg != yNeg && !tm.isZero()
	// r = t - k ln 2 in [0, ln 2).
	k := int64(nearest(float64(tHi * invLn2)))
	rNeg, r := signedAdd(tNeg, tm, k > 0, ln2Fx.mulSmall(uabs(k)))
	for rNeg {
		k--
		rNeg, r = signedAdd(rNeg, r, false, ln2Fx)
	}
	for !r.less(ln2Fx) {
		k++
		r = r.sub(ln2Fx)
	}
	// exp(r) in [1, 2).
	sum = fxInt(1)
	term = sum
	for n := uint64(1); ; n++ {
		term = term.mul(r).divSmall(n)
		if term.isZero() {
			break
		}
		sum = sum.add(term)
	}
	return roundScaled(sum, k)
}

// roundScaled is sum 2^k rounded to the nearest double, ties to even, sum in
// [1, 2).
func roundScaled(sum fx, k int64) float64 {
	if sum[5] >= 2 {
		sum, k = sum.shr(1), k+1
	}
	// Bits kept below the leading one.
	p := int64(52)
	if k < -1022 {
		p = 52 - (-1022 - k)
	}
	if p < -1 {
		return 0
	}
	shift := uint(320 - p)
	mant := sum.shr(shift)[0]
	rem := sum.low(shift)
	half := fxBit(shift - 1)
	tol := fxBit(70)
	var up bool
	switch {
	case half.add(tol).less(rem):
		up = true
	case rem.add(tol).less(half):
		up = false
	default:
		up = mant&1 == 1
	}
	if up {
		mant++
	}
	ex := k - p
	if mant == 1<<53 {
		mant >>= 1
		ex++
	}
	if mant >= 1<<52 {
		biased := ex + 52 + 1023
		if biased >= 2047 {
			return math.Inf(1)
		}
		return f(uint64(biased)<<52 | (mant - 1<<52))
	}
	return f(mant)
}

// powSlow is the slow path alone, for tests: it must agree with Pow
// everywhere.
func powSlow(x, y float64) float64 {
	m, e := reduce(x)
	t := ddMulF(lnDD(m, e), y)
	return slow(m, e, y, t.hi)
}
